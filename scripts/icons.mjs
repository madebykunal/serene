const root = fileURLToPath(new URL('..', import.meta.url));

function paths(file, weight) {
  const src = readFileSync(`${root}node_modules/phosphor-react-native/src/defs/${file}.tsx`, 'utf8');
  const start = src.indexOf(`'${weight}',`);
  if (start < 0) throw new Error(`${file}: no ${weight}`);
  const block = src.slice(start, src.indexOf('],', start));
  const tags = block.match(/<[A-Z][A-Za-z]*/g) ?? [];
  const other = tags.filter((t) => t !== '<Path');
  if (other.length) throw new Error(`${file} ${weight}: unsupported ${other.join(', ')}`);
  const ds = [...block.matchAll(/<Path\s+d="([^"]+)"\s*\/>/g)].map((m) => m[1]);
  if (ds.length !== tags.length) throw new Error(`${file} ${weight}: unexpected Path attributes`);
  return ds;
}

const lines = Object.entries(ICONS).map(([key, file]) => `  ${key}: [${JSON.stringify(paths(file, 'bold'))}, ${JSON.stringify(paths(file, 'regular'))}],`);
writeFileSync(
  `${root}src/ui/iconPaths.ts`,
  `// Generated by scripts/icons.mjs from Phosphor Icons (MIT): bold, then regular, on a 256 grid.\nexport const PATHS = {\n${lines.join('\n')}\n} satisfies Record<string, [string[], string[]]>;\n`,
);
